// node smoke.js : loads the page in headless Chromium, checks for errors, steers, tacks, auto-trims, screenshots.
import { launch, sleep } from './cdp.js';
import fs from 'fs';
import path from 'path';
const url = 'file://' + path.resolve('index.html');
const b = await launch({ width: 1400, height: 860, port: 9351 });
const errors = [];
let ok = 0, fail = 0;
const check = (name, cond, info = '') => { cond ? ok++ : fail++; console.log((cond ? 'ok   ' : 'FAIL ') + name + (info ? '  ' + info : '')); };
const shot = async (f) => { const r = await b.send('Page.captureScreenshot', { format: 'png' }); fs.writeFileSync(f, Buffer.from(r.result.data, 'base64')); };
try {
  await b.send('Page.navigate', { url });
  await sleep(2500);
  for (const e of b.events) if (e.method === 'Runtime.exceptionThrown') errors.push(e.params.exceptionDetails.exception?.description);
  check('no exceptions on load', errors.length === 0, errors.join('\n'));
  const bs = await b.evaluate("parseFloat(document.getElementById('r-bs').textContent)");
  check('boat is moving', bs > 1, bs + ' kn');
  check('coach has tips', await b.evaluate("document.querySelectorAll('#tips li').length") > 0);
  await shot('smoke_start.png');
  await b.evaluate("document.getElementById('auto').click()");
  await sleep(6000);
  const bs2 = await b.evaluate("parseFloat(document.getElementById('r-bs').textContent)");
  check('auto-trim keeps it sailing', bs2 > 3, bs2 + ' kn');
  await shot('smoke_auto.png');
  await b.evaluate("dispatchEvent(new KeyboardEvent('keydown',{key:' '}))");
  await sleep(9000);
  const tw = await b.evaluate("document.getElementById('r-tw').textContent");
  check('tacked onto port', / P$/.test(tw), tw);
  await shot('smoke_tacked.png');
  await b.evaluate("document.getElementById('preset').value='run'; document.getElementById('preset').dispatchEvent(new Event('change'))");
  await sleep(4000);
  await shot('smoke_run.png');
  await b.evaluate("document.querySelector('[data-head=spin]').click()");
  await sleep(500);
  check('spinnaker controls shown, jib hidden', await b.evaluate("getComputedStyle(document.getElementById('controls').querySelectorAll('input')[0]).display!=='none' && [...document.querySelectorAll('label')].find(l=>l.textContent==='Pole height').offsetParent!==null && [...document.querySelectorAll('label')].find(l=>l.textContent==='Jib car').offsetParent===null"));
  await b.evaluate("document.getElementById('auto').click()");
  await sleep(6000);
  const bsSpin = await b.evaluate("parseFloat(document.getElementById('r-bs').textContent)");
  check('spinnaker run faster than the jib run', bsSpin > 5.2, bsSpin + ' kn');
  await shot('smoke_spin.png');
  await b.evaluate("document.getElementById('preset').value='genReach'; document.getElementById('preset').dispatchEvent(new Event('change'))");
  await sleep(4000);
  await shot('smoke_gen.png');
  await b.evaluate("document.getElementById('preset').value='gale'; document.getElementById('preset').dispatchEvent(new Event('change'))");
  await sleep(4000);
  check('gale preset is reefed', await b.evaluate("document.querySelectorAll('output')[7].textContent") === '2 reefs', await b.evaluate("document.querySelectorAll('output')[7].textContent"));
  await shot('smoke_gale.png');
  await b.evaluate("const l=document.getElementById('loa'); l.value=45; l.dispatchEvent(new Event('input'))");
  await sleep(1500);
  check('boat length slider', await b.evaluate("SailModel.BOAT.loa") === 45);
  await b.evaluate("document.getElementById('preset').value='breezy'; document.getElementById('preset').dispatchEvent(new Event('change'))");
  await sleep(4000);
  await shot('smoke_breezy.png');
  for (const e of b.events) if (e.method === 'Runtime.exceptionThrown') errors.push(e.params.exceptionDetails.exception?.description);
  check('no exceptions at the end', errors.length === 0, errors.join('\n'));
} finally { b.kill(); }
console.log(`${ok} ok, ${fail} failed`);
process.exit(fail ? 1 : 0);
